#!/usr/bin/env node
// Writes dist/sw.js after `vite build`: an offline-first service worker that precaches
// every file of the build (star catalogue and Milky Way included) under a version derived
// from their content, so any change ships a fresh cache and the app never needs a network.
// Only used by the web / PWA build; the Android app serves its files locally.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(relative(dist, p).split('\\').join('/'));
  }
  return out;
}

const assets = walk(dist).filter((f) => f !== 'sw.js' && !f.endsWith('.map'));
const h = createHash('sha256');
for (const a of assets) { h.update(a); h.update(readFileSync(join(dist, a))); }
const version = h.digest('hex').slice(0, 12);

const sw = `// GENERATED by tools/build-sw.mjs - do not edit.
const VERSION = '${version}';
const CACHE = 'starfield-flight-' + VERSION;
const ASSETS = ${JSON.stringify(['./', ...assets.map((a) => './' + a)], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('starfield-flight-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./index.html').then((page) => page || fetch(req));
      return fetch(req);
    }),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);
const bytes = assets.reduce((n, a) => n + statSync(join(dist, a)).size, 0);
console.log(`wrote dist/sw.js: ${assets.length} files, ${(bytes / 1048576).toFixed(1)} MB precached, version ${version}`);
